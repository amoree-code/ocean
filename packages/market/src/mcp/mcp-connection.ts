import { readFileSync } from "node:fs";
import path from "node:path";
import {
  type CapabilityManifest,
  marketplaceIndexSchema,
} from "@ocean/core/domain/capabilities/capability-manifest.js";
import { enginePath, engineRoot } from "@ocean/core/shared/paths.js";
import type { McpServerSpec } from "../adapters/mcp-adapter.js";
import { literalArguments } from "./mcp-launch.js";

export type StdioMcpServer = {
  type: "stdio";
  command: string;
  args: string[];
  cwd: string;
};

export type PlaywrightMcpServer = {
  command: string;
  args: string[];
};

// The engine ships its own marketplace index (generated by scripts/generate-marketplace-index.mjs);
// client MCP configs are derived from the `mcp` capabilities in it rather than written here.
export function engineIndexFile(): string {
  return enginePath("ocean-marketplace.json");
}

function engineMcpCapability(name: string): CapabilityManifest {
  const index = marketplaceIndexSchema.parse(
    JSON.parse(readFileSync(engineIndexFile(), "utf8")),
  );
  const manifest = index.capabilities.find(
    (entry) => entry.kind === "mcp" && entry.name === name,
  );
  if (!manifest)
    throw new Error(`${name} is not an MCP capability in the engine index`);
  return manifest;
}

// A client config for one engine MCP capability, keyed the way clients already know it.
// `ocean-engine` packages run this Ocean (first-party, trusted, unsandboxed); `npm` packages run
// through npx. Third-party servers installed from a marketplace start via `ocean market exec`.
export function mcpClientConfig(name: string): {
  mcpServers: Record<string, StdioMcpServer | PlaywrightMcpServer>;
} {
  const server = engineMcpCapability(name).spec as McpServerSpec;
  const meta = (
    server._meta as Record<string, { clientKey?: string }> | undefined
  )?.["dev.ocean"];
  const key = meta?.clientKey ?? name.split("/").at(-1) ?? name;
  const item = server.packages?.[0];
  if (!item) throw new Error(`${name} has no package to run`);
  const args = literalArguments(
    item.packageArguments,
    `${name} packageArguments`,
  );
  if (item.registryType === "ocean-engine")
    return {
      mcpServers: {
        [key]: {
          type: "stdio",
          command: process.execPath,
          args: [path.join(engineRoot(), "dist", "main.js"), ...args],
          cwd: engineRoot(),
        },
      },
    };
  if (item.registryType === "npm")
    return {
      mcpServers: {
        [key]: {
          command: "npx",
          args: [
            typeof item.version === "string"
              ? `${item.identifier}@${item.version}`
              : String(item.identifier),
            ...args,
          ],
        },
      },
    };
  throw new Error(
    `${name}: registry type ${String(item.registryType)} has no client config`,
  );
}

export function oceanMcpConfig(): { mcpServers: { ocean: StdioMcpServer } } {
  return mcpClientConfig("dev.ocean/ocean") as {
    mcpServers: { ocean: StdioMcpServer };
  };
}

export function obsidianMcpConfig(): { mcpServers: { ocean: StdioMcpServer } } {
  return mcpClientConfig("dev.ocean/obsidian") as {
    mcpServers: { ocean: StdioMcpServer };
  };
}

export function playwrightMcpConfig(): {
  mcpServers: { playwright: PlaywrightMcpServer };
} {
  return mcpClientConfig("com.microsoft/playwright-mcp") as {
    mcpServers: { playwright: PlaywrightMcpServer };
  };
}
