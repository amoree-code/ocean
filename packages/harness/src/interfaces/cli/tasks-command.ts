export { listTasks };

// The live task an id-based action works on (resolution rules: resolveTaskReference). The
// action uses the location's own id and project, never the id as typed.
async function liveTask(
  id: string,
  explicitProject: string | undefined,
  cwdProject: string | null,
): Promise<{ owner: string; id: string; root: string }> {
  const location = await resolveTaskReference(id, {
    projectId: explicitProject ?? cwdProject ?? undefined,
    explicit: Boolean(explicitProject),
  });
  if (location.archived) throw new Error(`${location.id} is archived`);
  return {
    owner: location.projectId,
    id: location.id,
    root: resolveWithin(
      oceanPath(PROJECTS_DIR),
      projectFolder(location.projectId),
      "tasks",
    ),
  };
}

// `ocean tasks list --pretty`: one aligned row per task, for a person rather than a tool.
function taskTable(tasks: ProjectTask[]): string {
  if (!tasks.length) return "No tasks.\n";
  const rows = [
    ["PROJECT", "ID", "STATE", "TITLE"],
    ...tasks.map((task) => [task.project, task.id, task.state, task.title]),
  ];
  const widths = [0, 1, 2].map((column) =>
    Math.max(...rows.map((row) => row[column].length)),
  );
  return rows
    .map((row) =>
      row
        .map((cell, column) =>
          column < 3 ? cell.padEnd(widths[column]) : cell,
        )
        .join("  ")
        .trimEnd(),
    )
    .join("\n")
    .concat("\n");
}

export async function runTasksCommand(
  action: string,
  args: string[],
): Promise<void> {
  const projectIndex = args.indexOf("--project");
  const explicitProject =
    projectIndex >= 0 ? args[projectIndex + 1] : undefined;
  if (projectIndex >= 0 && !explicitProject)
    throw new Error("--project requires a project id");
  // Without --project, the tasks are the folder's project's (T-256): the cwd decides, and only a
  // folder that is no project falls back to the workspace project.
  const cwdProject = explicitProject
    ? null
    : await folderProject(process.cwd());
  const projectId = explicitProject ?? cwdProject ?? WORKSPACE_PROJECT_ID;
  if (action === "list") {
    const state = args.find(
      (arg, index) =>
        !arg.startsWith("--") &&
        (projectIndex < 0 || index !== projectIndex + 1),
    );
    const found = await listTasksForFolder({
      cwd: process.cwd(),
      project: explicitProject,
      state,
    });
    if (found.note) console.error(found.note);
    if (args.includes("--pretty")) process.stdout.write(taskTable(found.tasks));
    else console.log(JSON.stringify(found.tasks, null, 2));
    return;
  }
  if (action === "doctor") {
    try {
      const result = await execFile(process.execPath, [
        enginePath("scripts", "validate-tasks.mjs"),
        resolveWithin(
          oceanPath(PROJECTS_DIR),
          projectFolder(projectId),
          "tasks",
        ),
      ]);
      process.stdout.write(result.stdout);
    } catch (error) {
      const failure = error as Error & { stdout?: string; stderr?: string };
      if (failure.stdout) process.stdout.write(failure.stdout);
      if (failure.stderr) process.stderr.write(failure.stderr);
      process.exitCode = 1;
    }
    return;
  }
  if (action === "index") {
    const tasks = await listTasks(undefined, projectId);
    const body = [
      "# Tasks",
      "",
      "<!-- Generated by `ocean tasks index --write`. Do not edit by hand. -->",
      "",
      "| ID | State | Title | Goal |",
      "|---|---|---|---|",
      ...tasks.map(
        (task) =>
          `| ${task.id} | ${task.state} | ${task.title.replaceAll("|", "\\|")} | ${task.goal.replaceAll("|", "\\|")} |`,
      ),
      "",
    ].join("\n");
    const target = resolveWithin(
      oceanPath(PROJECTS_DIR),
      projectFolder(projectId),
      "index.md",
    );
    if (args.includes("--write")) {
      await writeFile(target, body, "utf8");
      console.log(`wrote ${path.relative(oceanPath(), target)}`);
    } else process.stdout.write(body);
    return;
  }
  if (action === "checkpoint") {
    const id = args.find((arg) => !arg.startsWith("--"));
    const noteIndex = args.indexOf("--note");
    const nextIndex = args.indexOf("--next");
    if (!id || noteIndex < 0 || !args[noteIndex + 1])
      throw new Error(
        "Usage: ocean tasks checkpoint <id> --note <text> [--next <text>] [--project <id>]",
      );
    const task = await liveTask(id, explicitProject, cwdProject);
    const result = await checkpointTask(task.id, task.root, {
      note: args[noteIndex + 1],
      next: nextIndex >= 0 ? args[nextIndex + 1] : undefined,
    });
    console.log(JSON.stringify({ ...result, project: task.owner }, null, 2));
    return;
  }
  if (action === "verify") {
    const id = args.find((arg) => !arg.startsWith("--"));
    if (!id) {
      console.error("Usage: ocean tasks verify <id> [--project <id>]");
      process.exitCode = 1;
      return;
    }
    const task = await liveTask(id, explicitProject, cwdProject);
    const outcome = await verifyTask(task.id, task.root);
    console.log(JSON.stringify(outcome, null, 2));
    if (!outcome.passed) process.exitCode = 1;
    return;
  }
  if (action === "complete") {
    const id = args[0];
    if (!id) {
      console.error("Usage: ocean tasks complete <id>");
      process.exitCode = 1;
      return;
    }
    if (args.includes("--no-verify")) {
      console.error("Task completion verification cannot be skipped.");
      process.exitCode = 1;
      return;
    }
    try {
      const task = await liveTask(id, explicitProject, cwdProject);
      console.log(
        JSON.stringify(await completeTask(task.id, task.root), null, 2),
      );
    } catch (error) {
      console.error(error instanceof Error ? error.message : String(error));
      process.exitCode = 1;
    }
    return;
  }
  if (action === "renumber") {
    const prefixIndex = args.indexOf("--prefix");
    const prefix = prefixIndex >= 0 ? args[prefixIndex + 1] : undefined;
    if (!explicitProject || !prefix)
      throw new Error(
        "Usage: ocean tasks renumber --project <id> --prefix <PREFIX> [--write]",
      );
    console.log(
      JSON.stringify(
        await renumberTasks({
          project: explicitProject,
          prefix,
          write: args.includes("--write"),
        }),
        null,
        2,
      ),
    );
    return;
  }
  if (action !== "archive") {
    console.error(
      "Usage: ocean tasks list [state] [--project <id>] [--pretty]|doctor|index [--write]|checkpoint <id> --note <text> [--next <text>]|verify <id>|complete <id>|archive [--apply|--auto]|renumber --project <id> --prefix <PREFIX> [--write]",
    );
    process.exitCode = 1;
    return;
  }
  const apply = args.includes("--apply") || args.includes("--auto");
  const result = await archiveDoneTasks(
    resolveWithin(oceanPath(PROJECTS_DIR), projectFolder(projectId), "tasks"),
    apply,
  );
  console.log(JSON.stringify({ dryRun: !apply, ...result }, null, 2));
  if (apply && result.skipped.length) process.exitCode = 1;
}
