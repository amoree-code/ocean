import { mkdir, readdir, readFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { claudeHiddenSkills } from "@ocean/context/context/context-cost.js";
import { atomicWrite } from "@ocean/core/shared/fs-utils.js";
import { oceanPath, SYSTEM_DIR } from "@ocean/core/shared/paths.js";

// The owner hides skills from Claude's model with `skillOverrides` (`off`,
// `user-invocable-only`). Codex and Gemini have no such setting and load every installed
// skill's description on every request, so `ocean client sync` disables the same skills there:
// a generated block of `[[skills.config]] enabled = false` entries in ~/.codex/config.toml, and
// names in `skills.disabled` of ~/.gemini/settings.json. Neither client can then use the skill
// at all, even explicitly; un-hiding it in Claude re-enables it on the next sync.

const BEGIN =
  "# ocean:skill-filter:begin — generated by `ocean client sync` from Claude's skillOverrides; edit those, not this";
const END = "# ocean:skill-filter:end";

export type SkillFilterResult = {
  client: "codex" | "gemini";
  file: string;
  status: "updated" | "current" | "missing" | "unparseable";
  disabled: number;
};

type Installed = { name: string; file: string };

// SKILL.md files directly under `root/<dir>/`, plus one category level deeper when `nested`.
async function installedSkills(
  root: string,
  nested: boolean,
): Promise<Installed[]> {
  const found: Installed[] = [];
  let entries: string[];
  try {
    entries = (await readdir(root)).sort();
  } catch {
    return found;
  }
  for (const entry of entries) {
    if (entry.startsWith(".") && !nested) continue;
    const file = path.join(root, entry, "SKILL.md");
    let text: string;
    try {
      text = await readFile(file, "utf8");
    } catch {
      if (nested)
        found.push(...(await installedSkills(path.join(root, entry), false)));
      continue;
    }
    const name =
      /^name:[ \t]*["']?([^"'\r\n]+?)["']?[ \t]*$/m.exec(
        text.split(/\r?\n---/)[0] ?? "",
      )?.[1] ?? entry;
    found.push({ name, file });
  }
  return found;
}

function codexBlock(files: string[]): string {
  const entries = files.map(
    (file) =>
      `[[skills.config]]\npath = ${JSON.stringify(file)}\nenabled = false\n`,
  );
  return `${BEGIN}\n${entries.join("\n")}${END}\n`;
}

async function syncCodex(
  home: string,
  hidden: Set<string>,
): Promise<SkillFilterResult> {
  const file = path.join(home, ".codex", "config.toml");
  const display = "~/.codex/config.toml";
  let text: string;
  try {
    text = await readFile(file, "utf8");
  } catch {
    return { client: "codex", file: display, status: "missing", disabled: 0 };
  }
  const skills = [
    ...(await installedSkills(path.join(home, ".codex", "skills"), true)),
    ...(await installedSkills(path.join(home, ".agents", "skills"), false)),
  ];
  const files = skills
    .filter((skill) => hidden.has(skill.name))
    .map((skill) => skill.file);
  const start = text.indexOf(BEGIN);
  const end = start === -1 ? -1 : text.indexOf(END, start);
  const hasBlock = start !== -1 && end > start;
  const block = files.length ? codexBlock(files) : "";
  let next: string;
  if (hasBlock) {
    const after = text.slice(end + END.length).replace(/^\r?\n/, "");
    next = `${text.slice(0, start)}${block}${after}`;
  } else if (block) {
    next = `${text}${text.endsWith("\n") || !text ? "" : "\n"}\n${block}`;
  } else next = text;
  if (next === text)
    return {
      client: "codex",
      file: display,
      status: "current",
      disabled: files.length,
    };
  await atomicWrite(file, next);
  return {
    client: "codex",
    file: display,
    status: "updated",
    disabled: files.length,
  };
}

function statePath(): string {
  return oceanPath(SYSTEM_DIR, "state", "skill-filter.json");
}

// Names Ocean put into Gemini's list, so un-hiding a skill in Claude takes it back out without
// touching the ones the owner disabled himself.
async function readAdded(): Promise<Set<string>> {
  try {
    const parsed = JSON.parse(await readFile(statePath(), "utf8"));
    return new Set(
      Array.isArray(parsed?.gemini)
        ? parsed.gemini.filter((name: unknown) => typeof name === "string")
        : [],
    );
  } catch {
    return new Set();
  }
}

async function syncGemini(
  home: string,
  hidden: Set<string>,
): Promise<SkillFilterResult> {
  const file = path.join(home, ".gemini", "settings.json");
  const display = "~/.gemini/settings.json";
  let text: string;
  try {
    text = await readFile(file, "utf8");
  } catch {
    return { client: "gemini", file: display, status: "missing", disabled: 0 };
  }
  let settings: Record<string, unknown>;
  try {
    const parsed = JSON.parse(text);
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed))
      throw new Error("not an object");
    settings = parsed;
  } catch {
    return {
      client: "gemini",
      file: display,
      status: "unparseable",
      disabled: 0,
    };
  }
  const installed = new Set(
    [
      ...(await installedSkills(path.join(home, ".gemini", "skills"), false)),
      ...(await installedSkills(path.join(home, ".agents", "skills"), false)),
    ].map((skill) => skill.name),
  );
  const wanted = [...hidden].filter((name) => installed.has(name)).sort();
  const skills =
    settings.skills && typeof settings.skills === "object"
      ? (settings.skills as Record<string, unknown>)
      : {};
  const current = Array.isArray(skills.disabled)
    ? skills.disabled.filter((name): name is string => typeof name === "string")
    : [];
  const previous = await readAdded();
  const owners = current.filter((name) => !previous.has(name));
  const next = [...owners, ...wanted.filter((name) => !owners.includes(name))];
  const added = wanted.filter((name) => !owners.includes(name));
  const record = async () => {
    if (JSON.stringify(added) === JSON.stringify([...previous].sort())) return;
    await mkdir(path.dirname(statePath()), { recursive: true });
    await atomicWrite(
      statePath(),
      `${JSON.stringify({ gemini: added }, null, 2)}\n`,
    );
  };
  if (JSON.stringify(next) === JSON.stringify(current)) {
    await record();
    return {
      client: "gemini",
      file: display,
      status: "current",
      disabled: wanted.length,
    };
  }
  const updated = { ...settings, skills: { ...skills, disabled: next } };
  await atomicWrite(file, `${JSON.stringify(updated, null, 2)}\n`);
  await record();
  return {
    client: "gemini",
    file: display,
    status: "updated",
    disabled: wanted.length,
  };
}

export async function syncSkillFilter(
  home = os.homedir(),
): Promise<SkillFilterResult[]> {
  const hidden = await claudeHiddenSkills(home);
  return [await syncCodex(home, hidden), await syncGemini(home, hidden)];
}
