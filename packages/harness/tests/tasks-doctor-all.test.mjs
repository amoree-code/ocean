import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";

const task = (id, project, state = "active") =>
  `---\nid: ${id}\ntitle: t\nstate: ${state}\nproject: ${project}\nopened: 2026-10-07\nupdated: 2026-10-07\nartifacts: []\n---\n\n## Objective\n\n## Definition of done\n\n## Next action\n\n## Verification\n\n## Blockers\n\n## Log\n`;

const generated = (rows) =>
  [
    "# Tasks",
    "",
    "<!-- Generated by `ocean tasks index --write`. Do not edit by hand. -->",
    "",
    "| ID | State | Title | Goal |",
    "|---|---|---|---|",
    ...rows.map(
      ([id, state]) => `| ${id} | ${state} | t | goal\nspanning lines |`,
    ),
    "",
  ].join("\n");

// projects: { id: { tasks: {ID: state}, index?: string } }
async function workspace(projects) {
  const root = await mkdtemp(path.join(os.tmpdir(), "ocean-doctor-all-"));
  for (const [project, { tasks, index }] of Object.entries(projects)) {
    const folder = path.join(root, "04-projects", project);
    for (const [id, state] of Object.entries(tasks)) {
      await mkdir(path.join(folder, "tasks", id), { recursive: true });
      await writeFile(
        path.join(folder, "tasks", id, "task.md"),
        task(id, project, state),
      );
    }
    if (index !== undefined)
      await writeFile(path.join(folder, "index.md"), index);
  }
  return root;
}

const validate = (root, project) =>
  spawnSync(
    process.execPath,
    [
      path.resolve("scripts/validate-tasks.mjs"),
      path.join(root, "04-projects", project, "tasks"),
    ],
    { encoding: "utf8" },
  );

test("a generated index that matches the records passes", async () => {
  const root = await workspace({
    lab: {
      tasks: { "LB-1": "active", "LB-2": "todo" },
      index: generated([
        ["LB-1", "active"],
        ["LB-2", "todo"],
      ]),
    },
  });
  try {
    const result = validate(root, "lab");
    assert.equal(result.status, 0, result.stderr);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("a generated index whose states, rows or tasks differ from the records is drift", async () => {
  const root = await workspace({
    lab: {
      tasks: { "LB-1": "active", "LB-2": "todo" },
      index: generated([
        ["LB-1", "todo"],
        ["LB-9", "active"],
      ]),
    },
  });
  try {
    const result = validate(root, "lab");
    assert.equal(result.status, 1);
    assert.match(result.stderr, /LB-1 is active, index says todo/);
    assert.match(result.stderr, /LB-2 is missing/);
    assert.match(result.stderr, /LB-9 is listed but not a live task/);
    assert.match(result.stderr, /ocean tasks index --write --project lab/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("a hand-written index is not checked", async () => {
  const root = await workspace({
    lab: {
      tasks: { "LB-1": "active" },
      index: "# Tasks\n\n| LB-1 | todo | t | g |\n",
    },
  });
  try {
    assert.equal(validate(root, "lab").status, 0);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("doctor --all checks every project and fails when any one drifts", async () => {
  const root = await workspace({
    ocean: { tasks: { "T-1": "active" } },
    lab: { tasks: { "LB-1": "active" }, index: generated([["LB-1", "todo"]]) },
  });
  try {
    const run = (...args) =>
      spawnSync(
        process.execPath,
        [path.resolve("dist/main.js"), "tasks", "doctor", ...args],
        {
          cwd: root,
          env: { ...process.env, OCEAN_ROOT: root },
          encoding: "utf8",
        },
      );
    const own = run("--project", "ocean");
    assert.equal(own.status, 0, own.stderr);
    const all = run("--all");
    assert.equal(all.status, 1);
    assert.match(all.stdout, /ocean: Validated 1 live/);
    assert.match(all.stderr, /lab: .*LB-1 is active, index says todo/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
